import { useState } from 'react';
import api from '../../services/api';
import { FiSearch, FiCheckCircle, FiXCircle, FiShield, FiFileText } from 'react-icons/fi';

const VerifyDocument = () => {
  const [code, setCode] = useState('');
  const [verificationResult, setVerificationResult] = useState(null);
  const [loading, setLoading] = useState(false);

  const handleVerify = async () => {
    if (!code.trim()) return;
    setLoading(true);
    setVerificationResult(null);
    try {
      const { data } = await api.get(`/documents/verify/${code.trim()}`);
      setVerificationResult(data);
    } catch (err) {
      setVerificationResult({
        valid: false,
        status: 'error',
        message: 'Verification failed. Please try again.',
      });
    } finally {
      setLoading(false);
    }
  };

  const handleKeyDown = (e) => {
    if (e.key === 'Enter') handleVerify();
  };

  return (
    <div className="min-h-screen bg-gradient-to-br from-blue-50 to-indigo-50 flex items-center justify-center p-4">
      <div className="max-w-lg w-full">
        <div className="text-center mb-8">
          <FiShield className="text-5xl text-blue-600 mx-auto mb-3" />
          <h1 className="text-3xl font-bold text-gray-800">Document Verification</h1>
          <p className="text-gray-500 mt-2">Verify the authenticity of school documents</p>
        </div>

        <div className="bg-white rounded-2xl shadow-lg p-6">
          {/* Input */}
          <div className="mb-6">
            <label className="block text-sm font-medium text-gray-700 mb-2">
              Enter Verification Code
            </label>
            <div className="flex gap-2">
              <input
                type="text"
                value={code}
                onChange={e => setCode(e.target.value.toUpperCase())}
                onKeyDown={handleKeyDown}
                placeholder="e.g., DOC-A1B2C3D4"
                className="flex-1 p-3 border rounded-lg focus:ring-2 focus:ring-blue-500 font-mono text-lg uppercase"
              />
              <button
                onClick={handleVerify}
                disabled={loading || !code.trim()}
                className={`px-6 py-3 rounded-lg font-medium transition ${
                  loading || !code.trim()
                    ? 'bg-gray-300 text-gray-500'
                    : 'bg-blue-600 text-white hover:bg-blue-700'
                }`}
              >
                {loading ? '...' : <><FiSearch className="inline" /> Verify</>}
              </button>
            </div>
          </div>

          {/* Result */}
          {verificationResult && (
            <div className={`p-6 rounded-xl border-2 ${
              verificationResult.valid
                ? 'border-green-200 bg-green-50'
                : 'border-red-200 bg-red-50'
            }`}>
              <div className="text-center mb-4">
                {verificationResult.valid ? (
                  <FiCheckCircle className="text-5xl text-green-500 mx-auto mb-2" />
                ) : (
                  <FiXCircle className="text-5xl text-red-500 mx-auto mb-2" />
                )}
                <h2 className={`text-xl font-bold ${
                  verificationResult.valid ? 'text-green-700' : 'text-red-700'
                }`}>
                  {verificationResult.valid ? 'Document Verified' : 'Verification Failed'}
                </h2>
                <p className="text-sm text-gray-600 mt-1">{verificationResult.message}</p>
              </div>

              {verificationResult.valid && verificationResult.data && (
                <div className="space-y-3 mt-4 border-t border-green-200 pt-4">
                  <div className="flex items-center justify-between text-sm">
                    <span className="text-gray-500">Document Type</span>
                    <span className="font-medium text-gray-800">
                      {verificationResult.data.templateName || verificationResult.data.documentType}
                    </span>
                  </div>
                  <div className="flex items-center justify-between text-sm">
                    <span className="text-gray-500">Issued At</span>
                    <span className="font-medium text-gray-800">
                      {new Date(verificationResult.data.issuedAt).toLocaleString('en-IN')}
                    </span>
                  </div>
                  <div className="flex items-center justify-between text-sm">
                    <span className="text-gray-500">Generated By</span>
                    <span className="font-medium text-gray-800">{verificationResult.data.generatedBy}</span>
                  </div>
                  <div className="flex items-center justify-between text-sm">
                    <span className="text-gray-500">Status</span>
                    <span className={`font-medium ${
                      verificationResult.data.status === 'valid' || verificationResult.data.status === 'issued'
                        ? 'text-green-600' : 'text-yellow-600'
                    }`}>
                      {verificationResult.data.status}
                    </span>
                  </div>
                  <div className="flex items-center justify-between text-sm">
                    <span className="text-gray-500">Verifications</span>
                    <span className="font-medium text-gray-800">{verificationResult.data.verificationCount} time(s)</span>
                  </div>
                </div>
              )}

              {!verificationResult.valid && (
                <div className="mt-4 border-t border-red-200 pt-4">
                  <p className="text-sm text-red-600">
                    Please contact the school administration if you believe this is an error.
                  </p>
                </div>
              )}
            </div>
          )}
        </div>

        <div className="text-center mt-6 text-xs text-gray-400">
          <FiFileText className="inline mr-1" />
          This verification system ensures the authenticity of documents issued by Fikr Smart School
        </div>
      </div>
    </div>
  );
};

export default VerifyDocument;
